def die(message: str, code: int = 2) -> None:
    print(f"live-security: {message}", file=sys.stderr)
    raise SystemExit(code)


def git_revision(repo: pathlib.Path) -> str:
    try:
        head = subprocess.run(
            ["git", "-C", str(repo), "rev-parse", "--short", "HEAD"],
            check=True, capture_output=True, text=True,
        ).stdout.strip()
        dirty = subprocess.run(
            ["git", "-C", str(repo), "status", "--porcelain"],
            check=True, capture_output=True, text=True,
        ).stdout
        return head + (" (dirty)" if dirty else " (clean)")
    except (OSError, subprocess.CalledProcessError) as error:
        return f"unknown ({error})"


def crate_version(repo: pathlib.Path) -> str:
    try:
        text = (repo / "Cargo.toml").read_text(encoding="utf-8")
    except OSError:
        return "unknown"
    for line in text.splitlines():
        if line.startswith("version"):
            return line.split("=", 1)[1].strip().strip('"')
    return "unknown"


def libc_version() -> str:
    try:
        return (ROOT / "VERSION").read_text(encoding="utf-8").strip()
    except OSError:
        return "unknown"


def sha256(path: pathlib.Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def qemu_version() -> str:
    try:
        return subprocess.run(
            ["qemu-system-riscv64", "--version"],
            check=True, capture_output=True, text=True,
        ).stdout.splitlines()[0]
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def cross_tool(name: str) -> str | None:
    """Resolve a cross tool from $CROSS (a prefix, as build.sh uses) or PATH."""
    cross = os.environ.get("CROSS", CROSS_DEFAULT)
    candidates = [cross + name, os.path.join(cross, "riscv-none-elf-" + name)]
    found = shutil.which("riscv-none-elf-" + name)
    if found:
        candidates.append(found)
    for candidate in candidates:
        if os.path.isfile(candidate):
            return candidate
    return None


def cross_nm() -> str | None:
    return cross_tool("nm")


def dl_state_address() -> int | None:
    """`dl_state` in build/ld-pagh.elf.  The audit's evil_bss_base variant
    stores through it and then jumps to the corrupted `objs[0].base`
    (`dl_state + 0x20`, `count` plus padding precede the object array)."""
    nm = cross_nm()
    if nm is None:
        return None
    try:
        out = subprocess.run(
            [nm, str(ROOT / "build" / "ld-pagh.elf")],
            check=True, capture_output=True, text=True,
        ).stdout
    except (OSError, subprocess.CalledProcessError):
        return None
    for line in out.splitlines():
        fields = line.split()
        if len(fields) == 3 and fields[2] == "dl_state":
            return int(fields[0], 16)
    return None


class Guest:
    """Serial-only QEMU driver: the guest's console is also its keyboard."""

    def __init__(self, kernel: pathlib.Path, disk: pathlib.Path, work: pathlib.Path):
        self.transcript = bytearray()
        self.serial = work / "serial.sock"
        for path in (self.serial,):
            if path.exists():
                path.unlink()
        self.proc = subprocess.Popen(
            [
                "qemu-system-riscv64",
                "-machine", "virt",
                "-bios", "default",
                "-m", "256M",
                "-device", "ramfb",
                "-kernel", str(kernel),
                "-serial", f"unix:{self.serial},server=on,wait=on",
                "-global", "virtio-mmio.force-legacy=false",
                "-display", "none",
                "-no-reboot",
                "-drive", f"file={disk},format=raw,if=none,id=hd0",
                "-device", "virtio-blk-device,drive=hd0",
            ],
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )
        self.sock = self._connect(self.serial)
        self._read_until_prompt(BOOT_TIMEOUT)

    @staticmethod
    def _connect(path: pathlib.Path) -> socket.socket:
        deadline = time.time() + 20.0
        while time.time() < deadline:
            candidate = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
            try:
                candidate.connect(str(path))
                return candidate
            except OSError:
                candidate.close()
                time.sleep(0.05)
        raise RuntimeError(f"cannot connect to the serial socket {path}")

    def _read_chunk(self, timeout: float) -> bool:
        self.sock.settimeout(0.25)
        deadline = time.time() + timeout
        got = False
        while time.time() < deadline:
            try:
                chunk = self.sock.recv(65536)
            except socket.timeout:
                continue
            except OSError:
                return got
            if not chunk:
                return got
            self.transcript += chunk
            got = True
        return got

    def _read_until_prompt(self, timeout: float) -> None:
        count = self.transcript.count(PROMPT)
        deadline = time.time() + timeout
        while time.time() < deadline:
            if self.transcript.count(PROMPT) > count:
                return
            if not self._read_chunk(0.5):
                continue
        raise RuntimeError("guest prompt did not appear")

    def run(self, command: str) -> None:
        baseline = self.transcript.count(PROMPT)
        # The guest polls a small UART FIFO; pace the bytes so a long program
        # path typed at once cannot outrun it.
        for byte in (command + "\n").encode("utf-8"):
            self.sock.sendall(bytes([byte]))
            time.sleep(0.01)
        deadline = time.time() + COMMAND_TIMEOUT
        while time.time() < deadline:
            if self.transcript.count(PROMPT) > baseline:
                break
            self._read_chunk(0.5)
        else:
            raise RuntimeError(f"no prompt after {command!r}")
        self._read_chunk(0.4)  # diagnostics printed right after the prompt

    def close(self) -> None:
        try:
            self.sock.close()
        except OSError:
            pass
        self.proc.terminate()
        try:
            self.proc.wait(timeout=5)
        except subprocess.TimeoutExpired:
            self.proc.kill()
            self.proc.wait(timeout=5)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--transcript",
        default=str(ROOT / "docs" / "live-security.txt"),
        help="where to write the committed transcript",
    )
    parser.add_argument(
        "--pagh-riscv",
        default=os.environ.get("PAGH_RISCV", str(ROOT.parent / "pagh-riscv")),
        help="pagh-riscv checkout (default ../pagh-riscv or $PAGH_RISCV)",
    )
    parser.add_argument(
        "--kernel",
        default=None,
        help="exact kernel ELF to boot instead of the build under --pagh-riscv "
             "(pins the image when another job may rebuild that checkout)",
    )
    parser.add_argument("--keep-workdir", action="store_true")
    args = parser.parse_args()

    kernel_repo = pathlib.Path(args.pagh_riscv).resolve()
    if args.kernel:
        kernel = pathlib.Path(args.kernel).resolve()
        if not kernel.is_file():
            die(f"--kernel {kernel} is not a file")
    else:
        kernel = kernel_repo / KERNEL_RELEASE
        if not kernel.is_file():
            kernel = kernel_repo / KERNEL_DEBUG
        if not kernel.is_file():
            die(f"no built kernel under {kernel_repo} (run `cargo build --release` there)")
    if shutil.which("qemu-system-riscv64") is None:
        die("qemu-system-riscv64 is required")
    if shutil.which("mke2fs") is None:
        die("mke2fs (e2fsprogs) is required")

    work = pathlib.Path(tempfile.mkdtemp(prefix="pagh-live-security-"))
    try:
        print("live-security: building the examples", file=sys.stderr)
        build = subprocess.run(["./build.sh"], cwd=ROOT, capture_output=True, text=True)
        if build.returncode != 0:
            print(build.stdout, file=sys.stderr)
            print(build.stderr, file=sys.stderr)
            die("build.sh failed")
        if "warning:" in build.stderr:
            print(build.stderr, file=sys.stderr)
            die("build.sh produced warnings")

        diskroot = work / "root"
        diskroot.mkdir()
        for pattern in ("build/*.elf",):
            for elf in ROOT.glob(pattern):
                shutil.copy(elf, diskroot / elf.stem)
        for shared in ROOT.glob("build/*.so"):
            shutil.copy(shared, diskroot / shared.name)
        if not (diskroot / "ld-pagh").is_file():
            die("build.sh did not produce build/ld-pagh.elf")

        # F-r3-rt-2: the audit's calloc victim plus the malloc/realloc sibling
        # checks are guest programs, compiled here against the library build
        # (the attack directory is not part of this repository).
        cc = cross_tool("gcc")
        if cc is None:
            die("riscv-none-elf-gcc is required for the allocator guests")
        guest_sources = (
            ("calloc_overflow_victim",
             "tests/security/calloc_overflow_victim.c"),
            ("alloc_bounds", "tests/security/alloc_bounds.c"),
        )
        for name, source in guest_sources:
            guest_build = subprocess.run(
                [
                    cc, "-march=rv64gc", "-mabi=lp64d",
                    "-mcmodel=medany", "-ffreestanding",
                    "-fno-stack-protector", "-fno-builtin", "-nostdlib",
                    "-O2", "-Wall", "-Wextra",
                    "-I", str(ROOT / "include"),
                    "-T", str(ROOT / "link.ld"),
                    str(ROOT / source), str(ROOT / "build" / "libpagh-c.a"),
                    "-lgcc", "-o", str(diskroot / name),
                ],
                capture_output=True, text=True,
            )
            if guest_build.returncode != 0:
                print(guest_build.stdout, file=sys.stderr)
                print(guest_build.stderr, file=sys.stderr)
                die(f"could not build {source}")
        # count = 4 (control) and the audit's untrusted same-heap-overflow
        # count, little endian, as the victim reads them.
        (diskroot / "rec_ok.bin").write_bytes((4).to_bytes(8, "little"))
        (diskroot / "rec_overflow.bin").write_bytes(
            (0x1000000000000001).to_bytes(8, "little")
        )
        print(
            "live-security: built calloc_overflow_victim and alloc_bounds",
            file=sys.stderr,
        )

        # The audit's crafted objects, generated at test time (the attack
        # directory is not part of this repository).
        make_evil = ROOT / "tests" / "security" / "make_evil_elf.py"
        dl_state = dl_state_address()
        if dl_state is None:
            print("live-security: warning: no cross nm; the loader-state variant "
                  "uses the same 0x4141... target", file=sys.stderr)
            store = 0x4141414141414141
        else:
            # struct dl_state { int count; /* pad */ struct dl_object objs[16]; }
            # and dl_object.base is its fourth pointer: +0x20 from dl_state.
            store = dl_state + 0x20
        crafted = [
            ("evil_state_abs", 0x4141414141414141, None, 16),
            ("evil_state_abs_bss", store, None, 16),
            ("evil_dyn_out", 0x4141414141414141, 0x4141414141414141, 16),
            ("evil_dyn_big", 0x4141414141414141, 0, 0x100000),
            ("evil_dyn_unaligned", 0x4141414141414141, 0x41, 16),
            ("evil_dyn_memsz", 0x4141414141414141, 0x80, 12),
        ]
        for name, target, dyn_vaddr, dyn_memsz in crafted:
            command = [
                sys.executable, str(make_evil), str(diskroot / name),
                "--target", hex(target), "--entry-stub",
            ]
            if dyn_vaddr is not None:
                command += ["--dyn-vaddr", hex(dyn_vaddr),
                            "--dyn-memsz", hex(dyn_memsz)]
            run = subprocess.run(command, capture_output=True, text=True)
            if run.returncode != 0:
                print(run.stdout, file=sys.stderr)
                print(run.stderr, file=sys.stderr)
                die(f"could not craft {name}")
        print(
            "live-security: crafted evil_state_abs(*, bss=0x%x), "
            "evil_dyn_out/big/unaligned/memsz" % store,
            file=sys.stderr,
        )

        # F-r2-libc-1: file-chosen constructor/fini call targets.
        make_init = ROOT / "tests" / "security" / "make_init_evil.py"
        init_run = subprocess.run(
            [sys.executable, str(make_init), str(diskroot)],
            capture_output=True, text=True,
        )
        if init_run.returncode != 0:
            print(init_run.stdout, file=sys.stderr)
            print(init_run.stderr, file=sys.stderr)
            die("could not craft the F-r2-libc-1 constructor objects")
        print(
            "live-security: crafted evil_call_abs/rel/absrel",
            file=sys.stderr,
        )

        disk = work / "disk.img"
        make = subprocess.run(
            [
                "mke2fs", "-q", "-t", "ext2", "-b", "1024", "-F",
                "-d", str(diskroot), str(disk), "16M",
            ],
            capture_output=True, text=True,
        )
        if make.returncode != 0:
            die(f"mke2fs failed: {make.stderr.strip()}")

        # The kernel checkout can be rebuilt by another job while this runs;
        # record the exact ELF that was booted and say so if it changed.
        kernel_sha = sha256(kernel)
        print("live-security: booting the kernel", file=sys.stderr)
        guest = Guest(kernel, disk, work)
        try:
            for command, _markers in COMMANDS:
                print(f"live-security: guest {command}", file=sys.stderr)
                guest.run(command)
        finally:
            guest.close()
        transcript = guest.transcript.decode("utf-8", "replace")
        if sha256(kernel) != kernel_sha:
            print("live-security: warning: the kernel ELF changed during the run; "
                  "the header records the sha256 of the booted copy", file=sys.stderr)

        header = "\n".join(
            [
                "# Live security acceptance for pagh-libc (runtime audits F-rt-1/F-rt-2/F-rt-3, F-r2-libc-1, F-r3-rt-2)",
                "# F-rt-1: ld-pagh SHN_ABS __pagh_dl_state cannot become an arbitrary store",
                "# F-rt-2: vsnprintf integer precision past the 32-byte digit buffer",
                "# F-rt-3: PT_DYNAMIC p_vaddr/p_memsz validated against the image",
                "# F-r2-libc-1: DT_INIT/DT_INIT_ARRAY/FINI targets validated; SHN_ABS relocation bounded",
                "# F-r3-rt-2: calloc n*size overflow refused (NULL/ENOMEM); malloc rounding and realloc old-size copied",
                f"# kernel: {kernel}"
                + (" (pinned with --kernel)" if args.kernel else ""),
                f"# kernel checkout: {kernel_repo} (revision {git_revision(kernel_repo)}, crate {crate_version(kernel_repo)})",
                f"# kernel sha256: {kernel_sha}",
                f"# pagh-libc: {libc_version()} (VERSION), revision {git_revision(ROOT)}",
                f"# host: {qemu_version()}",
                "# image: mke2fs -t ext2 -b 1024 -d <root with build/*.elf, build/*.so, "
                "tests/security/make_evil_elf.py and make_init_evil.py objects, "
                "calloc_overflow_victim/alloc_bounds, rec_ok.bin/rec_overflow.bin> disk.img",
                "# guest commands:",
                "\n".join(f"#   {command}" for command, _ in COMMANDS),
                "",
            ]
        )
        output = header + transcript
        if not transcript.endswith("\n"):
            output += "\n"
        pathlib.Path(args.transcript).write_text(output, encoding="utf-8")

        failed = False
        for forbidden in FORBIDDEN:
            if forbidden in transcript:
                print(f"live-security: FORBIDDEN in transcript: {forbidden}", file=sys.stderr)
                failed = True
        for command, markers in COMMANDS:
            for marker in markers:
                if marker not in transcript:
                    print(f"live-security: MISSING: {marker}", file=sys.stderr)
                    failed = True
        if failed:
            print(f"live-security: transcript is {args.transcript}", file=sys.stderr)
            return 1
        print(f"live-security: PASS (transcript {args.transcript})", file=sys.stderr)
        return 0
    finally:
        if args.keep_workdir:
            print(f"live-security: workdir kept at {work}", file=sys.stderr)
        else:
            shutil.rmtree(work, ignore_errors=True)


if __name__ == "__main__":
    sys.exit(main())