#!/usr/bin/env python3
"""Live security acceptance for the pagh-libc runtime audit fixes.

Four findings from the pagh round-1 and round-2 runtime audits are exercised
on the pagh-riscv guest, against a real kernel and the real `ld-pagh`/
`libpagh-c` build:

* **F-rt-1** — an ET_DYN that defines `__pagh_dl_state` as an `SHN_ABS` symbol
  must not turn the loader's `*slot = st` into a store to a file-chosen
  address (0x4141414141414141, or the loader's own `dl_state`, i.e. the
  `evil_bss_base` variant from the audit).  The crafted objects get a tiny
  entry stub (`li a0, 0; ret`), so "ran and exited 0" is the proof: with the
  bug the loader dies on the store page fault before the stub is reached.
* **F-rt-2** — `%.*d`/`%*.*u` with a precision past 32 (the audit's 33..112
  silent corruption and 128 return-address overwrite) must format, truncate
  and return lengths without touching the stack; the guest program
  `examples/printf_bounds.c` checks the contract.
* **F-rt-3** — a `PT_DYNAMIC` whose `p_vaddr`/`p_memsz` leave the mapped image
  or are unaligned must be rejected as a malformed ELF, not dereferenced; the
  audit's 369-byte `evil_arbread_dynamic.elf` used `p_vaddr =
  0x4141414141414141`.
* **F-r2-libc-1** — the loader validates where the dynamic table is but used
  to call the *values* in `DT_INIT`/`DT_INIT_ARRAY` unchecked, so a crafted
  ET_DYN put a file-chosen word in the loader's PC (0x4141414141414141), or
  used an `R_RISCV_RELATIVE`/`SHN_ABS` relocation to plant a file-chosen
  address in a writable `.init_array`, before the entry point was even
  checked.  `tests/security/make_init_evil.py` generates the three audit
  objects; the fixed loader must refuse each with
  `malformed ELF: unsafe DT_INIT_ARRAY` / `SHN_ABS symbol outside the image`
  and exit 1 instead of faulting.
* **F-r3-rt-2** — `calloc(n, size)` multiplied without an overflow check, so
  a parser that read an untrusted record count got an undersized block and
  wrote past it (the audit's store page fault ~68 KiB into the heap).
  `tests/security/calloc_overflow_victim.c` is the audit victim; the fixed
  library must answer the untrusted count with `CALLOC REFUSED`/exit 3 and
  still serve the count=4 control.  `tests/security/alloc_bounds.c` covers
  the code-evident siblings (`malloc` rounding wrap, `realloc` copying the
  new size from an unknown old one).

The harness boots the pagh-riscv kernel with the same QEMU configuration as
the kernel's own ``tools/run.py`` (the kernel repository is never modified),
builds the ext2 image with ``mke2fs -d`` from ``./build.sh`` output plus the
objects generated by ``tests/security/make_evil_elf.py``, and drives the shell
one prompt at a time: this test needs several guest programs, which one
``run.py --keys`` burst cannot sequence.  The serial transcript must contain
every marker below and no guest process may be killed; it is copied to
``docs/live-security.txt``.

Usage::

    ./build.sh
    python3 tools/live-security.py

``PAGH_RISCV`` selects the kernel checkout (default ``../pagh-riscv``); its
release ELF must already be built. QEMU and mke2fs are required.
"""

